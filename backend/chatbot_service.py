    def answer_query(self, message: str, language: str = "en", crop_context: Optional[str] = "Tomato") -> Dict[str, Any]:
        """Provides expert agronomic guidance in English, Kannada, Hindi, Telugu, Tamil, or Marathi."""
        msg_lower = message.lower().strip()
        lang = language.lower()

        # Detect script if language code is default
        if any('\u0c80' <= char <= '\u0cff' for char in message):
            lang = 'kn'
        elif any('\u0900' <= char <= '\u097f' for char in message):
            lang = 'hi' if lang != 'mr' else 'mr'
        elif any('\u0c00' <= char <= '\u0c7f' for char in message):
            lang = 'te'
        elif any('\u0b80' <= char <= '\u0bff' for char in message):
            lang = 'ta'

        if lang not in ["en", "kn", "hi", "te", "ta", "mr"]:
            lang = "en"

        # Determine topic
        if any(term in msg_lower for term in ["yellow", "turning yellow", "yellowing", "ಹಳದಿ", "पीली", "पीला", "పసుపు", "மஞ்சள்", "पिवळी"]):
            topic = "yellow_leaves"
        elif any(term in msg_lower for term in ["blight", "early blight", "late blight", "ಅಂಗಮಾರಿ", "झुलसा", "తెగులు", "கருகல்", "करपा"]):
            topic = "blight"
        elif any(term in msg_lower for term in ["soil", "npk", "fertilizer", "ph", "ಮಣ್ಣು", "ಗೊಬ್ಬರ", "मिट्टी", "खाद", "నేల", "ఎరువు", "மண்", "உரம்", "माती"]):
            topic = "soil_npk"
        elif any(term in msg_lower for term in ["seed", "germination", "ಬೀಜ", "ಮೊಳಕೆ", "बीज", "अंकुरण", "విత్తన", "మొలక", "விதை", "முளைப்பு", "बियाणे", "उगवण"]):
            topic = "seed_quality"
        elif any(term in msg_lower for term in ["rain", "weather", "spray", "ಮಳೆ", "ಹವಾಮಾನ", "मौसम", "बारिश", "వర్షం", "వాతావరణం", "மழை", "வானிலை", "पाऊस"]):
            topic = "weather"
        else:
            topic = "greeting"

        reply = RESPONSES[topic].get(lang, RESPONSES[topic]["en"])
        disclaimer = DISCLAIMERS.get(lang, DISCLAIMERS["en"])

        return {
            "query": message,
            "response": reply,
            "disclaimer": disclaimer,
            "language": lang
        }

